"""Builds the costar package, generating its costar.v1 gRPC stubs.

The stubs are generated from proto/costar/v1/costar.proto (in a costar
checkout, or the copy an sdist carries) with grpcio-tools, so they always
match the proto.  Generated code refuses to load with a runtime older than
its generator, so the package requires grpcio and protobuf at least as new
as the versions the stubs say they were generated by.  Nothing generated is
committed.
"""
from pathlib import Path
import re
import shutil
import tempfile

from setuptools import setup
from setuptools.command.build_py import build_py
from setuptools.command.sdist import sdist

HERE = Path(__file__).resolve().parent
PROTO = "costar/v1/costar.proto"


def proto_root():
    for root in (HERE / "proto", HERE.parent / "proto"):  # an sdist's copy, or the checkout's
        if (root / PROTO).is_file():
            return root
    raise RuntimeError(f"cannot find {PROTO}: build the costar package from a costar checkout")


def generate_stubs(out):
    from grpc_tools import protoc  # a build requirement

    (out / "costar" / "v1").mkdir(parents=True, exist_ok=True)
    args = ["protoc", f"-I{proto_root()}", f"--python_out={out}", f"--pyi_out={out}", f"--grpc_python_out={out}", PROTO]
    if protoc.main(args) != 0:
        raise RuntimeError("grpc_tools.protoc failed")
    (out / "costar" / "v1" / "__init__.py").touch()


def runtime_requirements():
    """grpcio and protobuf, at least as new as the generator of the stubs this
    build makes (older generators don't say, and need only the minimums)."""
    with tempfile.TemporaryDirectory() as out:
        generate_stubs(Path(out))
        v1 = Path(out) / "costar" / "v1"
        protobuf = re.search(r"^# Protobuf Python Version: (\d+\.\d+\.\d+)", (v1 / "costar_pb2.py").read_text(), re.M)
        grpc = re.search(r"^GRPC_GENERATED_VERSION = '([^']+)'", (v1 / "costar_pb2_grpc.py").read_text(), re.M)
    return [f"grpcio>={grpc[1] if grpc else '1.60'}", f"protobuf>={protobuf[1] if protobuf else '4.25'}"]


class BuildPy(build_py):
    def run(self):
        super().run()
        # An editable install imports from src/, so the stubs go there
        # (they are ignored by git).
        generate_stubs(HERE / "src" if self.editable_mode else Path(self.build_lib))


class Sdist(sdist):
    def make_release_tree(self, base_dir, files):
        super().make_release_tree(base_dir, files)
        target = Path(base_dir) / "proto" / PROTO
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(proto_root() / PROTO, target)


setup(cmdclass={"build_py": BuildPy, "sdist": Sdist}, install_requires=runtime_requirements())
